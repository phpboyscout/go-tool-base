type CommandFlag struct {
	Name          string
	Type          string
	Description   string
	Persistent    bool
	Shorthand     string
	Default       string
	DefaultIsCode bool
	Required      bool
	Hidden        bool
}

type CommandData struct {
	Package                  string
	PascalName               string
	Name                     string
	Aliases                  []string
	Args                     string
	Short                    string
	Long                     string
	Hidden                   bool
	WithAssets               bool
	Flags                    []CommandFlag
	PersistentFlags          []CommandFlag
	AncestralPersistentFlags []CommandFlag
	MutuallyExclusive        [][]string
	RequiredTogether         [][]string
	Logic                    string
	Imports                  []string
	FullFileContent          string
	TestCode                 string
	Recommendations          []string
	PersistentPreRun         bool
	PreRun                   bool
	HasSubcommands           bool
	// PureGroup marks a command that only groups its subcommands and so has no
	// run logic of its own — see Generator.pureGroup for how it is decided.
	// Such a command gets no Run<Name>, and its RunE is the framework's.
	PureGroup            bool
	WithInitializer      bool
	WithConfigValidation bool
	Hashes               map[string]string
	// MCPExposure controls whether the generated command stamps a
	// setup.ExcludeFromMCP / setup.IncludeInMCP marker. The zero value
	// (Inherit) emits nothing.
	MCPExposure setup.MCPExposure
}

func CommandRegistration(data CommandData) *jen.File {
	f := jen.NewFile(data.Package)
	f.HeaderComment("Code generated by gtb. DO NOT EDIT.")

	if data.WithAssets {
		f.Comment("//go:embed assets/*")
		f.Var().Id("assets").Qual("embed", "FS")
	}

	generateOptionsStruct(f, data)
	generateConstants(f, data)
	generateNewCmdFunction(f, data)

	return f
}

func generateConstants(f *jen.File, data CommandData) {
	var constants []jen.Code

	allFlags := append([]CommandFlag{}, data.Flags...)
	allFlags = append(allFlags, data.PersistentFlags...)
	allFlags = append(allFlags, data.AncestralPersistentFlags...)

	for _, flag := range allFlags {
		if c, ok := getConstantForFlag(flag); ok {
			constants = append(constants, c)
		}
	}

	if len(constants) > 0 {
		f.Const().Defs(constants...)
		f.Line()
	}
}

func getConstantForFlag(flag CommandFlag) (jen.Code, bool) {
	if flag.Default == "" || flag.DefaultIsCode {
		return nil, false
	}

	if flag.Type == "string" || flag.Type == "bool" || flag.Type == "" {
		return nil, false
	}

	constName := "default" + pascalCase(flag.Name)
	val := getConstantValue(flag)

	if val == nil {
		return nil, false
	}

	return jen.Id(constName).Op("=").Add(val), true
}

func getConstantValue(flag CommandFlag) jen.Code {
	switch flag.Type {
	case "int", "int32", "int64", "uint", "uint32", "uint64":
		return getIntConstantValue(flag)
	case "float64":
		f, _ := strconv.ParseFloat(flag.Default, 64)

		return jen.Id("float64").Call(jen.Lit(f))
	case "duration":
		return getDurationConstantValue(flag)
	}

	return nil
}

func getIntConstantValue(flag CommandFlag) jen.Code {
	// Explicitly type the constant to match the flag type.
	goType := flag.Type
	if goType == "" {
		goType = "int"
	}

	// Parse with the bit size appropriate for the target type so values
	// outside the target range produce an error rather than silent wrap.
	bitSize := intBitSize(goType)

	i, err := strconv.ParseInt(flag.Default, 10, bitSize)
	if err != nil {
		// Fall back to 0 on parse/overflow error; the generator's upstream
		// validation is expected to have caught this already.
		i = 0
	}

	if flag.Type == "int64" || flag.Type == "uint64" {
		return jen.Lit(i)
	}

	// jen.Lit accepts int64 directly; no narrowing required.
	return jen.Id(goType).Call(jen.Lit(i))
}

const (
	intBits32 = 32
	intBits64 = 64
)

// intBitSize returns the bit size to pass to strconv.ParseInt for the given
// Go integer type. Unsized types (int, uint) are parsed at 64 bits because
// the generated code runs on the target platform, not the build host.
func intBitSize(goType string) int {
	switch goType {
	case "int32", "uint32":
		return intBits32
	case "int64", "uint64", "int", "uint":
		return intBits64
	default:
		return intBits64
	}
}

func getDurationConstantValue(flag CommandFlag) jen.Code {
	d := parseDuration(flag.Default)

	switch {
	case d%time.Hour == 0 && d > 0:
		return jen.Lit(int(d.Hours())).Op("*").Qual("time", "Hour")
	case d%time.Minute == 0 && d > 0:
		return jen.Lit(int(d.Minutes())).Op("*").Qual("time", "Minute")
	case d%time.Second == 0 && d > 0:
		return jen.Lit(int(d.Seconds())).Op("*").Qual("time", "Second")
	case d%time.Millisecond == 0 && d > 0:
		return jen.Lit(int(d.Milliseconds())).Op("*").Qual("time", "Millisecond")
	default:
		return jen.Qual("time", "Duration").Call(jen.Lit(int(d)))
	}
}

func parseDuration(s string) time.Duration {
	if s == "" {
		return 0
	}

	// If it's just a number, treat as seconds
	if _, err := time.ParseDuration(s); err != nil {
		if d, err := time.ParseDuration(s + "s"); err == nil {
			return d
		}
	} else if d, err := time.ParseDuration(s); err == nil {
		return d
	}

	return 0
}

func generateOptionsStruct(f *jen.File, data CommandData) {
	f.Type().Id(data.PascalName + "Options").StructFunc(func(g *jen.Group) {
		// Duplicated ancestral persistent flags
		for _, flag := range data.AncestralPersistentFlags {
			addFlagToStruct(g, flag)
		}

		// Own persistent flags
		for _, flag := range data.PersistentFlags {
			addFlagToStruct(g, flag)
		}

		// Own normal flags
		for _, flag := range data.Flags {
			if flag.Persistent {
				continue
			}

			addFlagToStruct(g, flag)
		}
	})
	f.Line()
}

func addFlagToStruct(g *jen.Group, flag CommandFlag) {
	typeName := flag.Type
	if typeName == "" {
		typeName = "string"
	}
	// Map manifest types to Go types
	goType := typeName
	switch typeName {
	case "stringSlice", "stringslice", "stringArray", "stringarray":
		goType = "[]string"
	case "intSlice", "intslice":
		goType = "[]int"
	case "int32":
		goType = "int32"
	case "uint":
		goType = "uint"
	case "uint32":
		goType = "uint32"
	case "uint64":
		goType = "uint64"
	case "duration":
		g.Id(pascalCase(flag.Name)).Qual("time", "Duration")

		return
	}

	g.Id(pascalCase(flag.Name)).Id(goType)
}

func generateNewCmdFunction(f *jen.File, data CommandData) {
	returns := []jen.Code{
		jen.Op("*").Qual("gitlab.com/phpboyscout/go-tool-base/pkg/setup", "Command"),
	}

	params := []jen.Code{
		jen.Id("props").Op("*").Qual("gitlab.com/phpboyscout/go-tool-base/pkg/props", "Props"),
	}

	f.Func().Id("NewCmd" + data.PascalName).Params(params...).Params(returns...).BlockFunc(func(g *jen.Group) {
		if data.WithAssets {
			g.Id("props").Dot("Assets").Dot("Register").Call(jen.Lit(data.Name), jen.Op("&").Id("assets"))
			g.Line()
		}

		if needsOpts(data) {
			g.Id("opts").Op(":=").Op("&").Id(data.PascalName + "Options").Block()
			g.Line()
		}

		cmdFields := generateCommandFields(data)

		// cmd is *setup.Command from the start so any later parent.Register(...)
		// AST insertion or in-body subcommand attachment goes through the
		// composed type. setup.Wrap returns *setup.Command which embeds
		// *cobra.Command, so cmd.Flags(), cmd.MarkFlagsMutuallyExclusive,
		// and friends still chain through the embedded pointer.
		//
		// Go implicitly converts the untyped string constant to the named
		// props.FeatureID type, so we emit a literal rather than
		// props.FeatureID("<name>"). The literal avoids shadowing the
		// `props` parameter with the `props` package import inside this
		// function body.
		g.Id("cmd").Op(":=").Qual("gitlab.com/phpboyscout/go-tool-base/pkg/setup", "Wrap").Call(
			jen.Lit(data.Name),
			jen.Op("&").Qual("github.com/spf13/cobra", "Command").Block(cmdFields...),
		)
		g.Line()

		generateMCPExposure(g, data.MCPExposure)

		addFlagsToCommand(g, data.Flags, data.PersistentFlags)
		generateMutuallyExclusive(g, data.MutuallyExclusive)
		generateRequiredTogether(g, data.RequiredTogether)

		g.Return(jen.Id("cmd"))
	})
}

// generateMCPExposure emits the MCP-exposure marker for the command, if any:
// setup.ExcludeFromMCP(cmd) for an excluded command, setup.IncludeInMCP(cmd)
// for an explicitly exposed one (which overrides an excluded ancestor), and
// nothing for the inherit/default case.
func generateMCPExposure(g *jen.Group, exposure setup.MCPExposure) {
	const setupPkg = "gitlab.com/phpboyscout/go-tool-base/pkg/setup"

	switch exposure {
	case setup.MCPExposureExcluded:
		g.Qual(setupPkg, "ExcludeFromMCP").Call(jen.Id("cmd"))
		g.Line()
	case setup.MCPExposureExposed:
		g.Qual(setupPkg, "IncludeInMCP").Call(jen.Id("cmd"))
		g.Line()
	case setup.MCPExposureInherit:
		// No explicit decision — emit nothing; the command inherits.
	}
}

func CommandInitializer(data CommandData) *jen.File {
	f := jen.NewFile(data.Package)
	f.HeaderComment("Code generated by gtb. DO NOT EDIT.")

	f.Line()
	f.Func().Id("init").Params().Block(
		jen.Qual("gitlab.com/phpboyscout/go-tool-base/pkg/setup", "Register").Call(
			jen.Qual("gitlab.com/phpboyscout/go-tool-base/pkg/props", "FeatureID").Call(jen.Lit(data.Name)),
			jen.Index().Qual("gitlab.com/phpboyscout/go-tool-base/pkg/setup", "InitialiserProvider").Values(
				jen.Func().Params(jen.Id("p").Op("*").Qual("gitlab.com/phpboyscout/go-tool-base/pkg/props", "Props")).Qual("gitlab.com/phpboyscout/go-tool-base/pkg/setup", "Initialiser").Block(
					jen.If(jen.Id("skip"+data.PascalName)).Block(jen.Return(jen.Nil())),
					jen.Return(jen.Op("&").Id(data.PascalName+"Initialiser").Block()),
				),
			),
			jen.Index().Qual("gitlab.com/phpboyscout/go-tool-base/pkg/setup", "SubcommandProvider").Values(
				jen.Func().Params(jen.Id("p").Op("*").Qual("gitlab.com/phpboyscout/go-tool-base/pkg/props", "Props")).Index().Op("*").Qual("github.com/spf13/cobra", "Command").Block(
					jen.Return(jen.Index().Op("*").Qual("github.com/spf13/cobra", "Command").Values(jen.Id("NewCmdInit"+data.PascalName).Call(jen.Id("p")))),
				),
			),
			jen.Index().Qual("gitlab.com/phpboyscout/go-tool-base/pkg/setup", "FeatureFlag").Values(
				jen.Func().Params(jen.Id("cmd").Op("*").Qual("github.com/spf13/cobra", "Command")).Block(
					jen.Id("cmd").Dot("Flags").Call().Dot("BoolVar").Call(
						jen.Op("&").Id("skip"+data.PascalName),
						jen.Lit("skip-"+data.Name),
						jen.False(),
						jen.Lit("skip initializing "+data.Name+" configuration"),
					),
				),
			),
		),
	)

	f.Var().Id("skip" + data.PascalName).Bool()

	f.Line()
	f.Type().Id(data.PascalName + "Initialiser").Struct()

	f.Func().Params(jen.Id("i").Op("*").Id(data.PascalName + "Initialiser")).Id("Name").Params().String().Block(
		jen.Return(jen.Lit(data.Name)),
	)

	f.Func().Params(jen.Id("i").Op("*").Id(data.PascalName + "Initialiser")).Id("IsConfigured").Params(jen.Id("cfg").Qual("gitlab.com/phpboyscout/go/config", "Reader")).Bool().Block(
		jen.Return(jen.Id("cfg").Dot("IsSet").Call(jen.Lit(data.Name))),
	)

	// The leading context.Context is required by setup.Initialiser. It is
	// forwarded to the user's Init<Name> stub rather than discarded, so a
	// scaffolded initialiser can honour cancellation and per-operation
	// deadlines — which is why the interface carries it at all.
	f.Func().Params(jen.Id("i").Op("*").Id(data.PascalName+"Initialiser")).Id("Configure").Params(
		jen.Id("ctx").Qual("context", "Context"),
		jen.Id("p").Op("*").Qual("gitlab.com/phpboyscout/go-tool-base/pkg/props", "Props"),
		jen.Id("cfg").Qual("gitlab.com/phpboyscout/go-tool-base/pkg/setup", "Editor"),
	).Error().Block(
		jen.Return(jen.Id("Init"+data.PascalName).Call(jen.Id("ctx"), jen.Id("p"), jen.Id("cfg"))),
	)

	f.Line()
	f.Func().Id("NewCmdInit"+data.PascalName).Params(
		jen.Id("p").Op("*").Qual("gitlab.com/phpboyscout/go-tool-base/pkg/props", "Props"),
	).Op("*").Qual("github.com/spf13/cobra", "Command").Block(
		jen.Return(jen.Op("&").Qual("github.com/spf13/cobra", "Command").Values(jen.Dict{
			jen.Id("Use"):   jen.Lit(data.Name),
			jen.Id("Short"): jen.Lit("Initialise " + data.Name + " configuration"),
			jen.Id("RunE"): jen.Func().Params(jen.Id("cmd").Op("*").Qual("github.com/spf13/cobra", "Command"), jen.Id("_").Index().String()).Error().Block(
				jen.List(jen.Id("editor"), jen.Id("_"), jen.Err()).Op(":=").Qual("gitlab.com/phpboyscout/go-tool-base/pkg/setup", "OpenConfigEditor").Call(
					jen.Id("cmd").Dot("Context").Call(),
					jen.Id("p"),
					jen.Qual("gitlab.com/phpboyscout/go-tool-base/pkg/setup", "GetDefaultConfigDir").Call(jen.Id("p").Dot("FS"), jen.Id("p").Dot("Tool").Dot("Name")),
					jen.False(),
				),
				jen.If(jen.Err().Op("!=").Nil()).Block(jen.Return(jen.Err())),
				jen.Return(jen.Id("Init"+data.PascalName).Call(jen.Id("cmd").Dot("Context").Call(), jen.Id("p"), jen.Id("editor"))),
			),
		})),
	)

	return f
}

func needsOpts(data CommandData) bool {
	// A command that calls its own Run<Name> needs opts to pass it; so does one
	// with a hook or a flag. A pure group's RunE is setup.GroupRunE, which takes
	// neither props nor opts, so it declares neither.
	return !data.PureGroup || data.PersistentPreRun || data.PreRun ||
		len(data.Flags) > 0 || len(data.PersistentFlags) > 0 || len(data.AncestralPersistentFlags) > 0
}

func generateCommandFields(data CommandData) []jen.Code {
	cmdFields := []jen.Code{
		jen.Id("Use").Op(":").Lit(commandUse(data)).Op(","),
		jen.Id("Short").Op(":").Add(litOrRaw(data.Short)).Op(","),
		jen.Id("Long").Op(":").Add(litOrRaw(data.Long)).Op(","),
	}

	if argsField := generateArgsField(data.Args); argsField != nil {
		cmdFields = append(cmdFields, argsField)
	}

	if len(data.Aliases) > 0 {
		cmdFields = append(cmdFields, jen.Id("Aliases").Op(":").Index().String().ValuesFunc(func(g *jen.Group) {
			for _, alias := range data.Aliases {
				g.Lit(alias)
			}
		}).Op(","))
	}

	if data.Hidden {
		cmdFields = append(cmdFields, jen.Id("Hidden").Op(":").True().Op(","))
	}

	if data.PersistentPreRun {
		cmdFields = append(cmdFields, jen.Id("PersistentPreRunE").Op(":").Func().Params(
			jen.Id("cmd").Op("*").Qual("github.com/spf13/cobra", "Command"),
			jen.Id("args").Index().String(),
		).Error().Block(
			jen.If(
				jen.Id("cmd").Dot("Parent").Call().Op("!=").Nil().
					Op("&&").Id("cmd").Dot("Parent").Call().Dot("PersistentPreRunE").Op("!=").Nil(),
			).Block(
				jen.If(
					jen.Id("err").Op(":=").Id("cmd").Dot("Parent").Call().Dot("PersistentPreRunE").Call(jen.Id("cmd"), jen.Id("args")).Op(";").
						Id("err").Op("!=").Nil(),
				).Block(
					jen.Return(jen.Id("err")),
				),
			),
			jen.Return(
				jen.Id("PersistentPreRun"+data.PascalName).Call(
					jen.Id("cmd").Dot("Context").Call(),
					jen.Id("props"),
					jen.Id("opts"),
					jen.Id("args"),
				),
			),
		).Op(","))
	}

	cmdFields = append(cmdFields, generatePreRunField(data))

	// Every command wires RunE, groups included — a command that is not Runnable
	// never evaluates Args, so cobra answers a mistyped subcommand with help and
	// success (spec 0190).
	//
	// What it wires depends on whether the command has run logic of its own. A
	// PURE group has none, so its RunE is the framework's: usage and success when
	// bare, a named error on a verb it does not have. Nothing in the developer's
	// own package is referenced, which is what makes this immune both to the dead
	// stub of issue #21 and to the seal that produced issue #22 — a seal governs
	// what the generator writes, and can no longer reach what the tool does.
	if data.PureGroup {
		cmdFields = append(cmdFields, jen.Id("RunE").Op(":").
			Qual("gitlab.com/phpboyscout/go-tool-base/pkg/setup", "GroupRunE").Op(","))
	} else {
		cmdFields = append(cmdFields, jen.Id("RunE").Op(":").Func().Params(
			jen.Id("cmd").Op("*").Qual("github.com/spf13/cobra", "Command"),
			jen.Id("args").Index().String(),
		).Error().Block(
			jen.Return(
				jen.Id("Run"+data.PascalName).Call(
					jen.Id("cmd").Dot("Context").Call(),
					jen.Id("props"),
					jen.Id("opts"),
					jen.Id("args"),
				),
			),
		).Op(","))
	}

	return cmdFields
}

func generatePreRunField(data CommandData) jen.Code {
	return jen.Id("PreRunE").Op(":").Func().Params(
		jen.Id("cmd").Op("*").Qual("github.com/spf13/cobra", "Command"),
		jen.Id("args").Index().String(),
	).Error().BlockFunc(func(bg *jen.Group) {
		// Pull ancestral persistent flag values
		for _, flag := range data.AncestralPersistentFlags {
			pullFlag(bg, flag)
		}

		bg.Id("props").Dot("ErrorHandler").Dot("SetUsage").Call(jen.Id("cmd").Dot("Usage"))

		if data.PreRun {
			bg.Return(
				jen.Id("PreRun"+data.PascalName).Call(
					jen.Id("cmd").Dot("Context").Call(),
					jen.Id("props"),
					jen.Id("opts"),
					jen.Id("args"),
				),
			)
		} else {
			bg.Return(jen.Nil())
		}
	}).Op(",")
}

func generateMutuallyExclusive(g *jen.Group, groups [][]string) {
	for _, group := range groups {
		if len(group) > 1 {
			args := make([]jen.Code, 0, len(group))
			for _, flagName := range group {
				args = append(args, jen.Lit(flagName))
			}

			g.Id("cmd").Dot("MarkFlagsMutuallyExclusive").Call(args...)
		}
	}
}

func generateRequiredTogether(g *jen.Group, groups [][]string) {
	for _, group := range groups {
		if len(group) > 1 {
			args := make([]jen.Code, 0, len(group))
			for _, flagName := range group {
				args = append(args, jen.Lit(flagName))
			}

			g.Id("cmd").Dot("MarkFlagsRequiredTogether").Call(args...)
		}
	}
}

func addFlagsToCommand(g *jen.Group, flags []CommandFlag, persistentFlags []CommandFlag) {
	// Add ancestral persistent flags (already bound in parent, but we might want to bind them here if we want local access?
	// Actually in cobra, persistent flags are inherited. We only need to bind them if we want to OVERRIDE or if we are the ones DEFINING them.
	// But our "functional" model means we have a local copy of the value.
	// Wait, if we define them again here, it might conflict?
	// Cobra: "Persistent Flags: A flag can be persistent, meaning that this flag will be available to the command it's assigned to as well as every command under that command."
	// So we don't re-define ancestral flags. We only bind OUR OWN flags.
	// Our 'populate' callback handles receiving values from parents.

	// Add normal flags
	for _, flag := range flags {
		if flag.Persistent {
			continue
		}

		addFlag(g, flag, false)
	}

	// Add persistent flags
	for _, flag := range persistentFlags {
		addFlag(g, flag, true)
	}

	if len(flags) > 0 || len(persistentFlags) > 0 {
		g.Line()
	}
}

func addFlag(g *jen.Group, flag CommandFlag, isPersistent bool) {
	funcName, defaultVal := getFlagFunctionAndDefault(flag)

	if flag.Shorthand != "" {
		funcName += "P"
	}

	fGroup := jen.Id("cmd").Dot("Flags").Call()
	if isPersistent {
		fGroup = jen.Id("cmd").Dot("PersistentFlags").Call()
	}

	args := []jen.Code{
		jen.Op("&").Id("opts").Dot(pascalCase(flag.Name)),
		jen.Lit(flag.Name),
	}

	if flag.Shorthand != "" {
		args = append(args, jen.Lit(flag.Shorthand))
	}

	args = append(args, defaultVal, litOrRaw(flag.Description))

	g.Add(fGroup.Dot(funcName).Call(args...))

	if flag.Required {
		markFuncName := "MarkFlagRequired"
		if isPersistent {
			markFuncName = "MarkPersistentFlagRequired"
		}

		g.Id("_").Op("=").Id("cmd").Dot(markFuncName).Call(jen.Lit(flag.Name))
	}

	if flag.Hidden {
		g.Id("_").Op("=").Id("cmd").Dot("Flags").Call().Dot("MarkHidden").Call(jen.Lit(flag.Name))
	}
}

func pullFlag(g *jen.Group, flag CommandFlag) {
	funcSuffix := "String"

	switch flag.Type {
	case "bool":
		funcSuffix = "Bool"
	case "int":
		funcSuffix = "Int"
	case "float64":
		funcSuffix = "Float64"
	case "stringSlice", "stringslice":
		funcSuffix = "StringSlice"
	case "stringArray", "stringarray":
		funcSuffix = "StringArray"
	case "intSlice", "intslice":
		funcSuffix = "IntSlice"
	case "int64":
		funcSuffix = "Int64"
	case "duration":
		funcSuffix = "Duration"
	}

	g.If(
		jen.List(jen.Id("v"), jen.Id("err")).Op(":=").Id("cmd").Dot("Flags").Call().Dot("Get"+funcSuffix).Call(jen.Lit(flag.Name)),
		jen.Id("err").Op("==").Nil(),
	).Block(
		jen.Id("opts").Dot(pascalCase(flag.Name)).Op("=").Id("v"),
	)
}

func getFlagFunctionAndDefault(flag CommandFlag) (string, jen.Code) {
	funcName := getFlagFuncName(flag.Type)
	defaultVal := getFlagDefaultValue(flag)

	return funcName, defaultVal
}

func getFlagFuncName(flagType string) string {
	if fn, ok := flagFuncMap[flagType]; ok {
		return fn
	}

	return "StringVar"
}

var flagFuncMap = map[string]string{
	"bool":        "BoolVar",
	"int":         "IntVar",
	"float64":     "Float64Var",
	"stringSlice": "StringSliceVar",
	"stringslice": "StringSliceVar",
	"stringArray": "StringArrayVar",
	"stringarray": "StringArrayVar",
	"intSlice":    "IntSliceVar",
	"intslice":    "IntSliceVar",
	"int32":       "Int32Var",
	"int64":       "Int64Var",
	"uint":        "UintVar",
	"uint32":      "Uint32Var",
	"uint64":      "Uint64Var",
	"duration":    "DurationVar",
}

func getFlagDefaultValue(flag CommandFlag) jen.Code {
	if flag.Default == "" {
		return getZeroValue(flag.Type)
	}

	if flag.DefaultIsCode {
		// The default is emitted verbatim as Go source. Both input
		// boundaries (generator.ValidateManifest on the manifest path,
		// the generate-command CLI path) gate the value through
		// generator.ValidateFlagDefaultCode, which restricts it to a
		// bare identifier or dot-joined selector (e.g. time.Second).
		return jen.Id(flag.Default)
	}

	switch flag.Type {
	case "bool":
		if flag.Default == "true" {
			return jen.True()
		}

		return jen.False()
	case "stringSlice", "stringslice", "stringArray", "stringarray":
		return getStringSliceDefault(flag.Default)
	case "intSlice", "intslice":
		return getIntSliceDefault(flag.Default)
	case "int", "float64", "int32", "int64", "uint", "uint32", "uint64", "duration":
		return jen.Id("default" + pascalCase(flag.Name))
	}

	// Default to string literal
	return jen.Lit(flag.Default)
}

func getZeroValue(flagType string) jen.Code {
	switch flagType {
	case "bool":
		return jen.False()
	case "int", "int32", "int64", "uint", "uint32", "uint64", "duration":
		return jen.Lit(0)
	case "float64":
		return jen.Lit(0.0)
	case "stringSlice", "stringslice", "stringArray", "stringarray":
		return jen.Index().String().Values()
	case "intSlice", "intslice":
		return jen.Index().Int().Values()
	}

	return jen.Lit("")
}

func getStringSliceDefault(def string) jen.Code {
	if def == "[]" {
		return jen.Index().String().Values()
	}

	parts := strings.Split(def, ",")
	vals := make([]jen.Code, len(parts))

	for i, p := range parts {
		vals[i] = jen.Lit(strings.TrimSpace(p))
	}

	return jen.Index().String().Values(vals...)
}

func getIntSliceDefault(def string) jen.Code {
	if def == "[]" {
		return jen.Index().Int().Values()
	}

	parts := strings.Split(def, ",")
	vals := make([]jen.Code, len(parts))

	for i, p := range parts {
		iv, _ := strconv.Atoi(strings.TrimSpace(p))
		vals[i] = jen.Lit(iv)
	}

	return jen.Index().Int().Values(vals...)
}

// CommandConfigValidation generates the content for a config.go file containing
// a Config struct stub and a ValidateConfig function for per-package schema validation.
func CommandConfigValidation(data CommandData) string {
	var sb strings.Builder
	sb.WriteString("package " + data.Package + "\n\n")
	sb.WriteString("import (\n")
	sb.WriteString("\t\"gitlab.com/phpboyscout/go/config\"\n")
	sb.WriteString(")\n\n")

	fmt.Fprintf(&sb, "// %sConfig describes the configuration keys consumed by %s.\n", data.PascalName, data.Name)
	fmt.Fprintf(&sb, "type %sConfig struct {\n", data.PascalName)
	fmt.Fprintf(&sb, "\t// TODO: Add config fields with struct tags.\n")
	fmt.Fprintf(&sb, "\t// Example:\n")
	fmt.Fprintf(&sb, "\t// APIKey   string `config:\"%s.api_key\" validate:\"required\"`\n", data.Name)
	fmt.Fprintf(&sb, "\t// LogLevel string `config:\"%s.log_level\" enum:\"debug,info,warn,error\" default:\"info\"`\n", data.Name)
	sb.WriteString("}\n\n")

	fmt.Fprintf(&sb, "// Validate%sConfig checks that all required %s config keys are present\n", data.PascalName, data.Name)
	fmt.Fprintf(&sb, "// and that constrained values are within their allowed sets.\n")
	fmt.Fprintf(&sb, "func Validate%sConfig(cfg config.Reader) error {\n", data.PascalName)
	fmt.Fprintf(&sb, "\treturn config.ValidateStruct[%sConfig](cfg)\n", data.PascalName)
	sb.WriteString("}\n")

	return sb.String()
}

func CommandExecution(data CommandData) string {
	if data.FullFileContent != "" {
		return data.FullFileContent
	}

	cleanImports := getCleanImports(data.Imports, data.WithInitializer, !data.PureGroup)

	var sb strings.Builder
	sb.WriteString("package " + data.Package + "\n\n")
	sb.WriteString("import (\n")

	for _, imp := range cleanImports {
		if strings.Contains(imp, "\"") {
			sb.WriteString("\t" + imp + "\n")
		} else {
			sb.WriteString("\t\"" + imp + "\"\n")
		}
	}

	sb.WriteString(")\n\n")

	if data.PersistentPreRun {
		fmt.Fprintf(&sb, "func PersistentPreRun%s(ctx context.Context, props *props.Props, opts *%sOptions, args []string) error {\n", data.PascalName, data.PascalName)
		sb.WriteString("\tprops.Logger.Info(\"Running persistent pre run for " + data.Name + "\")\n")
		sb.WriteString("\treturn nil\n")
		sb.WriteString("}\n\n")
	}

	if data.PreRun {
		fmt.Fprintf(&sb, "func PreRun%s(ctx context.Context, props *props.Props, opts *%sOptions, args []string) error {\n", data.PascalName, data.PascalName)
		sb.WriteString("\tprops.Logger.Info(\"Running pre run for " + data.Name + "\")\n")
		sb.WriteString("\treturn nil\n")
		sb.WriteString("}\n\n")
	}

	// A pure group has no run function at all: its cmd.go wires setup.GroupRunE,
	// so there is nothing here to call and nothing to leave unreachable.
	if !data.PureGroup {
		fmt.Fprintf(&sb, "func Run%s(ctx context.Context, props *props.Props, opts *%sOptions, args []string) error {\n", data.PascalName, data.PascalName)

		if data.Logic != "" {
			sb.WriteString(data.Logic)
			sb.WriteString("\n")
		} else {
			sb.WriteString("\treturn errorhandling.ErrNotImplemented\n")
		}

		sb.WriteString("}\n")
	}

	if data.WithInitializer {
		sb.WriteString("\n")
		fmt.Fprintf(&sb, "func Init%s(ctx context.Context, p *props.Props, cfg setup.Editor) error {\n", data.PascalName)
		sb.WriteString("\t// TODO: Implement custom initialization logic for " + data.Name + "\n")
		sb.WriteString("\treturn nil\n")
		sb.WriteString("}\n")
	}

	return sb.String()
}

func getCleanImports(rawImports []string, withInitializer, withRunStub bool) []string {
	uniqueImports := make(map[string]bool)

	var cleanImports []string

	// Add base imports first
	baseImports := []string{
		"context",
		"gitlab.com/phpboyscout/go-tool-base/pkg/props",
	}

	// Only the generated Run<Name> stub names a sentinel, and a pure group has
	// no Run<Name>. Importing it anyway would not compile.
	if withRunStub {
		baseImports = append(baseImports, "gitlab.com/phpboyscout/go/errorhandling")
	}

	// The generated Init<Name> stub takes a setup.Editor, so pkg/setup is
	// required in main.go when an initializer is generated.
	if withInitializer {
		baseImports = append(baseImports, "gitlab.com/phpboyscout/go-tool-base/pkg/setup")
	}

	for _, imp := range baseImports {
		uniqueImports[imp] = true
		cleanImports = append(cleanImports, imp)
	}

	for _, imp := range rawImports {
		if isRedundantImport(imp) {
			continue
		}

		if _, exists := uniqueImports[imp]; !exists {
			uniqueImports[imp] = true
			cleanImports = append(cleanImports, imp)
		}
	}

	return cleanImports
}

func isRedundantImport(imp string) bool {
	// Skip redundant props or context imports from AI
	if strings.HasSuffix(imp, "/props") || imp == "context" || imp == "io" || imp == "os" || imp == "fmt" {
		return true
	}

	// Skip hallucinated logger
	if imp == "github.com/phpboyscout/logger" ||
		imp == "github.com/charmbracelet/log" ||
		imp == "charm.land/log/v2" {
		return true
	}

	return false
}

func pascalCase(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool {
		return r == '-' || r == '_' || r == ' '
	})
	for i, part := range parts {
		if len(part) > 0 {
			parts[i] = strings.ToUpper(part[:1]) + part[1:]
		}
	}

	return strings.Join(parts, "")
}

func litOrRaw(s string) jen.Code {
	if strings.Contains(s, "\n") && !strings.Contains(s, "`") {
		return jen.Id("`" + s + "`")
	}

	return jen.Lit(s)
}

func generateArgsField(args string) jen.Code {
	if args == "" {
		return nil
	}

	callName := strings.Split(args, "(")[0]

	return jen.Id("Args").Op(":").Qual("github.com/spf13/cobra", callName).Add(func() jen.Code {
		if !strings.Contains(args, "(") {
			return jen.Null()
		}

		argStr := strings.TrimSuffix(strings.Split(args, "(")[1], ")")
		if argStr == "" {
			return jen.Call()
		}

		// Check if it's a number
		if i, err := strconv.Atoi(argStr); err == nil {
			return jen.Call(jen.Lit(i))
		}

		return jen.Call(jen.Id(argStr))
	}()).Op(",")
}
