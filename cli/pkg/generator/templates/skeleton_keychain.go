package templates

import (
	"github.com/dave/jennifer/jen"

	"gitlab.com/phpboyscout/go-tool-base/pkg/setup/keychain"
)

// SkeletonKeychain generates cmd/<name>/keychain.go for scaffolded projects,
// blank-importing pkg/setup/keychain, which links the go-keyring-backed
// backend and declares the keychain feature as a link kind (spec 0199 OQ3).
// The file is the feature: the manifest's keychain entry writes or removes it
// (spec 0197 D8), and a build without it links no keychain IPC code, which an
// SBOM against the artefact can verify.
func SkeletonKeychain() *jen.File {
	f := jen.NewFile("main")
	f.HeaderComment("Code generated by gtb. DO NOT EDIT.")
	f.PackageComment("Activates OS keychain support by blank-importing the")
	f.PackageComment("framework's keychain link, which registers the go-keyring")
	f.PackageComment("backend and declares the feature. Toggle it with")
	f.PackageComment("`gtb enable keychain` / `gtb disable keychain`; a build")
	f.PackageComment("without this file carries no keychain IPC code. See")
	f.PackageComment("docs/how-to/configure-credentials.md in the GTB repo.")

	f.Anon(keychain.PackagePath)

	return f
}
