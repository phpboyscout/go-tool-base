func TestSkeletonExternalAdapter(t *testing.T) {
	t.Parallel()

	src := SkeletonExternalAdapter()

	_, err := parser.ParseFile(token.NewFileSet(), "attach.go", src, parser.ParseComments)
	require.NoError(t, err, src)

	assert.Contains(t, src, "package external")
	assert.Contains(t, src, "func Commands(p *props.Props) []*setup.Command {")
	assert.Contains(t, src, "this file is yours to edit")
	assert.NotContains(t, src, "DO NOT EDIT", "the adapter is author-owned, not generated output")
}

func TestIsExternalArgToken(t *testing.T) {
	t.Parallel()

	for _, tok := range ExternalArgTokens {
		assert.Truef(t, IsExternalArgToken(tok), "%s is in the vocabulary", tok)
	}

	assert.False(t, IsExternalArgToken("os.Exit(1)"))
	assert.False(t, IsExternalArgToken(""))
}
