func TestSkeletonTrustKeys(t *testing.T) {
	t.Parallel()

	src := renderGoFile(t, SkeletonTrustKeys())

	assert.Contains(t, src, "// Code generated by gtb. DO NOT EDIT.")
	assert.Contains(t, src, "package trustkeys")
	assert.Contains(t, src, "//go:embed all:keys\nvar keyFS embed.FS")
	assert.Contains(t, src, "func Keys() [][]byte {")
	assert.Contains(t, src, `fs.WalkDir(keyFS, "keys", func(p string, d fs.DirEntry, err error) error {`)
	assert.Contains(t, src, `if path.Ext(p) != ".asc" {`)
	assert.Contains(t, src, "b, readErr := keyFS.ReadFile(p)")
	assert.Contains(t, src, "out = append(out, b)")
}

