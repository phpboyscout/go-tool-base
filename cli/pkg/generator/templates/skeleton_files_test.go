func TestSkeletonSigning(t *testing.T) {
	t.Parallel()

	t.Run("no posture is a no-op init", func(t *testing.T) {
		t.Parallel()

		src := renderGoFile(t, SkeletonSigning(SkeletonSigningData{}))

		assert.Contains(t, src, "package root")
		assert.Contains(t, src, "func init() {}")
		assert.Contains(t, src, "No enforcement posture configured yet.")
		assert.NotContains(t, src, "verify.")
	})

	t.Run("full posture", func(t *testing.T) {
		t.Parallel()

		src := renderGoFile(t, SkeletonSigning(SkeletonSigningData{
			ExternalKeyEmail:          "release@example.org",
			RequireSignature:          true,
			KeySource:                 "both",
			RequireExternalCrosscheck: true,
		}))

		assert.Contains(t, src, `"gitlab.com/phpboyscout/go/signing/verify"`)
		assert.Contains(t, src, "verify.DefaultRequireSignature = true")
		assert.Contains(t, src, `verify.DefaultKeySource = "both"`)
		assert.Contains(t, src, "verify.DefaultRequireExternalCrosscheck = true")
		assert.Contains(t, src, `verify.DefaultExternalKeyEmail = "release@example.org"`)
		assert.NotContains(t, src, "No enforcement posture")
	})

	t.Run("only the stated values", func(t *testing.T) {
		t.Parallel()

		src := renderGoFile(t, SkeletonSigning(SkeletonSigningData{KeySource: "embedded"}))

		assert.Contains(t, src, `verify.DefaultKeySource = "embedded"`)
		assert.NotContains(t, src, "DefaultRequireSignature")
		assert.NotContains(t, src, "DefaultExternalKeyEmail")
	})
}

