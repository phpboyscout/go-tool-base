package generator

import (
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/spf13/afero"
)

// Generation provenance that the renderer does NOT put into the generated source
// — template-overlay identity/pins, the signing posture, and module_published —
// is recorded as structured `// gtb:...` annotations in a dedicated generated
// file so `gtb regenerate manifest` can reconstruct it from scratch. The file is
// tracked in-tree (so it survives a `.gtb/` deletion) and has no runtime effect.
//
// It lives beside the root command and is skipped by the command scanner. It is
// emitted only when there is something to record, and removed otherwise, so a
// plain project carries no extra file.

const provenanceFileName = "provenance.go"

// provenancePath returns the provenance file path for a project.
func provenancePath(projectPath string) string {
	return filepath.Join(projectPath, "pkg", "cmd", "root", provenanceFileName)
}

// renderProvenanceFile builds the provenance file content from a manifest,
// returning ok=false when there is nothing to record.
func renderProvenanceFile(m *Manifest) (string, bool) {
	var ann []string

	if m.Properties.Signing.Enabled {
		ann = append(ann, "// gtb:signing "+encodeKV(signingFields(m.Properties.Signing)))
	}

	for _, t := range m.Properties.Templates {
		ann = append(ann, "// gtb:template "+encodeKV(templateFields(t)))
	}

	if m.Properties.ModulePublished {
		ann = append(ann, "// gtb:module published=true")
	}

	if len(ann) == 0 {
		return "", false
	}

	var b strings.Builder

	b.WriteString("// Code generated by gtb. DO NOT EDIT.\n//\n")
	b.WriteString("// Generation provenance not present elsewhere in the generated source, so\n")
	b.WriteString("// `gtb regenerate manifest` can reconstruct it from scratch. No runtime effect.\n//\n")

	for _, a := range ann {
		b.WriteString(a + "\n")
	}

	b.WriteString("\npackage root\n")

	return b.String(), true
}

// applyProvenanceFile recovers the signing, template, and module_published
// properties from the provenance file into a from-scratch manifest. A missing
// file means the project recorded no such provenance.
func (g *Generator) applyProvenanceFile(props *ManifestProperties) {
	data, err := afero.ReadFile(g.props.FS, provenancePath(g.config.Path))
	if err != nil {
		return
	}

	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)

		switch {
		case strings.HasPrefix(line, "// gtb:signing "):
			props.Signing = signingFromKV(decodeKV(strings.TrimPrefix(line, "// gtb:signing ")))
		case strings.HasPrefix(line, "// gtb:template "):
			props.Templates = append(props.Templates, templateFromKV(decodeKV(strings.TrimPrefix(line, "// gtb:template "))))
		case strings.HasPrefix(line, "// gtb:module "):
			props.ModulePublished = decodeKV(strings.TrimPrefix(line, "// gtb:module "))["published"] == "true"
		}
	}
}

// writeProvenanceFile emits the provenance file when there is something to record
// and removes it otherwise, keeping generate and regenerate in sync. It is a
// no-op unless something is recorded / already present.
func (g *Generator) writeProvenanceFile(m *Manifest) error {
	path := provenancePath(g.config.Path)

	content, ok := renderProvenanceFile(m)
	if !ok {
		// Nothing to record: drop any stale provenance file.
		if exists, _ := afero.Exists(g.props.FS, path); exists {
			return g.props.FS.Remove(path)
		}

		return nil
	}

	// The provenance file lives beside the root command; ensure the directory
	// exists (a manifest may be written before the skeleton dir on some paths).
	if err := g.props.FS.MkdirAll(filepath.Dir(path), os.FileMode(DefaultDirMode)); err != nil {
		return err
	}

	return afero.WriteFile(g.props.FS, path, []byte(content), os.FileMode(DefaultFileMode))
}

// signingFields serialises the recoverable signing posture. Hashes and other
// derivable data are excluded — this is provenance/config only. Every value
// written here is gated by validateManifestSigning (ValidateManifest), whose
// character classes exclude whitespace and control bytes, so no field can
// break the space-separated KV encoding or escape the comment line.
func signingFields(s ManifestSigning) []kv {
	return []kv{
		{"enabled", strconv.FormatBool(s.Enabled)},
		{"external_key_email", s.ExternalKeyEmail},
		{"require_signature", boolField(s.RequireSignature)},
		{"key_source", s.KeySource},
		{"require_external_crosscheck", boolField(s.RequireExternalCrosscheck)},
		{"backend", s.Backend},
		{"key_id", s.KeyID},
		{"kms_region", s.KMSRegion},
		{"public_key", s.PublicKey},
	}
}

func signingFromKV(m map[string]string) ManifestSigning {
	return ManifestSigning{
		Enabled:                   m["enabled"] == "true",
		ExternalKeyEmail:          m["external_key_email"],
		RequireSignature:          m["require_signature"] == "true",
		KeySource:                 m["key_source"],
		RequireExternalCrosscheck: m["require_external_crosscheck"] == "true",
		Backend:                   m["backend"],
		KeyID:                     m["key_id"],
		KMSRegion:                 m["kms_region"],
		PublicKey:                 m["public_key"],
	}
}

// templateFields serialises a template overlay's provenance and pins. Per-file
// Hashes are excluded — they are recomputed when the overlay is re-applied.
func templateFields(t TemplateSource) []kv {
	return []kv{
		{"name", t.Name},
		{"type", string(t.Type)},
		{"location", t.Location},
		{"ref", t.Ref},
		{"resolved", t.Resolved},
		{"fingerprint", t.Fingerprint},
	}
}

func templateFromKV(m map[string]string) TemplateSource {
	return TemplateSource{
		Name:        m["name"],
		Type:        TemplateSourceType(m["type"]),
		Location:    m["location"],
		Ref:         m["ref"],
		Resolved:    m["resolved"],
		Fingerprint: m["fingerprint"],
	}
}

type kv struct {
	key, value string
}

// boolField renders a bool, omitting the false case (encodeKV drops empties) so
// the annotation stays minimal.
func boolField(b bool) string {
	if b {
		return "true"
	}

	return ""
}

// encodeKV renders key=value pairs space-separated, skipping empty values. The
// values recorded here (emails, ARNs, repo paths, refs, SHAs) are token-like
// with no spaces, so a space separator is unambiguous.
func encodeKV(pairs []kv) string {
	parts := make([]string, 0, len(pairs))

	for _, p := range pairs {
		if p.value == "" {
			continue
		}

		parts = append(parts, p.key+"="+p.value)
	}

	return strings.Join(parts, " ")
}

// decodeKV parses the space-separated key=value form produced by encodeKV.
func decodeKV(s string) map[string]string {
	out := map[string]string{}

	for _, tok := range strings.Fields(s) {
		if k, v, ok := strings.Cut(tok, "="); ok {
			out[k] = v
		}
	}

	return out
}
