func TestGenerateManPage_SinglePageToWriter(t *testing.T) {
	t.Parallel()

	var buf bytes.Buffer
	err := docs.GenerateManPage(&buf, fixtureTree(), docs.ManOptions{Source: "demo 1.0.0"})
	require.NoError(t, err)

	out := buf.String()
	// Only the root page is rendered, with GTB's header policy applied: the
	// .TH header carries the defaulted manual title and no auto-gen trailer.
	// The root's own NAME section is present; the subcommand's description is
	// not (its page would be separate), confirming this is a single page.
	assert.Contains(t, out, ".TH")
	assert.Contains(t, out, "Demo Manual")
	assert.Contains(t, out, "demo - demo root")
	assert.NotContains(t, out, "Auto generated by spf13/cobra")
	assert.NotContains(t, out, "build things")
}

