func TestGenerateManTree_Reproducible(t *testing.T) {
	t.Parallel()

	read := func() []byte {
		dir := t.TempDir()
		require.NoError(t, docs.GenerateManTree(fixtureTree(), docs.ManOptions{
			Dir:    dir,
			Source: "demo 1.0.0",
			Manual: "Demo Manual",
		}))
		data, err := os.ReadFile(filepath.Join(dir, "man1", "demo.1"))
		require.NoError(t, err)

		return data
	}

	// With Date nil the auto-gen trailer is suppressed, so two runs are
	// byte-identical (SOURCE_DATE_EPOCH-independent within the same month).
	first := read()
	second := read()
	assert.Equal(t, first, second)
}

func TestGenerateManTree_DateStamped(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	when := time.Date(2026, time.June, 21, 0, 0, 0, 0, time.UTC)
	require.NoError(t, docs.GenerateManTree(fixtureTree(), docs.ManOptions{
		Dir:    dir,
		Source: "demo 1.0.0",
		Manual: "Demo Manual",
		Date:   &when,
	}))

	data, err := os.ReadFile(filepath.Join(dir, "man1", "demo.1"))
	require.NoError(t, err)
	assert.Contains(t, string(data), "Jun 2026", "explicit --date is stamped into .TH")
}

