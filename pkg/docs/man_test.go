func TestManPagePaths_SectionDefaultAndOverride(t *testing.T) {
	t.Parallel()

	def := docs.ManPagePaths(fixtureTree(), docs.ManOptions{Dir: "out"})
	assert.Contains(t, def, filepath.Join("out", "man1", "demo.1"))

	sec8 := docs.ManPagePaths(fixtureTree(), docs.ManOptions{Dir: "out", Section: "8"})
	assert.Contains(t, sec8, filepath.Join("out", "man8", "demo.8"))
}

func TestManSource(t *testing.T) {
	t.Parallel()

	withVer := &props.Props{Version: version.Info{Version: "1.2.3"}}
	assert.Equal(t, "demo 1.2.3", docs.ManSource("demo", withVer))

	noVer := &props.Props{Version: version.Info{}}
	assert.Equal(t, "demo", docs.ManSource("demo", noVer))

	assert.Equal(t, "demo", docs.ManSource("demo", nil))
}
