// fixtureTree builds a small command tree: root "demo" with a "build"
// subcommand that itself has a "now" subcommand.
func fixtureTree() *cobra.Command {
	root := &cobra.Command{Use: "demo", Short: "demo root", Long: "The demo root command."}
	build := &cobra.Command{Use: "build", Short: "build things", Run: func(*cobra.Command, []string) {}}
	now := &cobra.Command{Use: "now", Short: "build now", Run: func(*cobra.Command, []string) {}}
	build.AddCommand(now)
	root.AddCommand(build)

	return root
}

func TestGenerateManTree_WritesPagePerCommand(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	err := docs.GenerateManTree(fixtureTree(), docs.ManOptions{
		Dir:    dir,
		Source: "demo 1.0.0",
		Manual: "Demo Manual",
	})
	require.NoError(t, err)

	for _, name := range []string{"demo.1", "demo-build.1", "demo-build-now.1"} {
		path := filepath.Join(dir, "man1", name)
		assert.FileExistsf(t, path, "expected man page %s", name)
	}
}

func TestGenerateManTree_HeaderPolicy(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	require.NoError(t, docs.GenerateManTree(fixtureTree(), docs.ManOptions{
		Dir:    dir,
		Source: "demo 1.0.0",
		Manual: "Demo Manual",
	}))

	data, err := os.ReadFile(filepath.Join(dir, "man1", "demo.1"))
	require.NoError(t, err)
	roff := string(data)

	assert.Contains(t, roff, "demo 1.0.0", "configured Source must appear in .TH")
	assert.Contains(t, roff, "Demo Manual", "configured Manual must appear in .TH")
	assert.NotContains(t, roff, "Auto generated by spf13/cobra",
		"the cobra placeholder must never ship")
}

